-- Esquema normalizado (3FNBC) del sistema de inventarios
CREATE SCHEMA inventario;
SET search_path = inventario, public;

-- Una subcategoría apunta a su categoría padre
CREATE TABLE categorias (
    categoria_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(80) NOT NULL UNIQUE,
    categoria_padre_id  INT REFERENCES categorias (categoria_id),
    CONSTRAINT ck_categorias_padre_distinto
        CHECK (categoria_padre_id IS NULL OR categoria_padre_id <> categoria_id)
);

CREATE TABLE proveedores (
    proveedor_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL UNIQUE,
    contacto      VARCHAR(100) NOT NULL,
    telefono      VARCHAR(20)  NOT NULL,
    pais          VARCHAR(60)  NOT NULL,
    CONSTRAINT ck_proveedores_telefono
        CHECK (telefono ~ '^\+?[0-9][0-9 -]{6,18}$')
);

CREATE TABLE almacenes (
    almacen_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80)  NOT NULL UNIQUE,
    ubicacion   VARCHAR(150) NOT NULL
);


CREATE TABLE productos (
    producto_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(20)   NOT NULL UNIQUE,
    nombre          VARCHAR(120)  NOT NULL,
    categoria_id    INT           NOT NULL REFERENCES categorias (categoria_id),
    proveedor_id    INT           NOT NULL REFERENCES proveedores (proveedor_id),
    costo_unitario  NUMERIC(12,2) NOT NULL,
    precio_venta    NUMERIC(12,2) NOT NULL,
    activo          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_productos_sku    CHECK (sku ~ '^[A-Z]{3}-[0-9]{3}$'),
    CONSTRAINT ck_productos_costo  CHECK (costo_unitario >= 0),
    CONSTRAINT ck_productos_precio CHECK (precio_venta >= 0)
);

-- stock_optimo no viene en el Anexo 1; se agrega para calcular la reposición
CREATE TABLE stock_almacen (
    producto_id   INT NOT NULL REFERENCES productos (producto_id),
    almacen_id    INT NOT NULL REFERENCES almacenes (almacen_id),
    cantidad      INT NOT NULL DEFAULT 0,
    stock_minimo  INT NOT NULL,
    stock_optimo  INT NOT NULL,
    pasillo       VARCHAR(5)  NOT NULL,
    estante       VARCHAR(10) NOT NULL,
    PRIMARY KEY (producto_id, almacen_id),
    CONSTRAINT ck_stock_cantidad CHECK (cantidad >= 0),
    CONSTRAINT ck_stock_minimo   CHECK (stock_minimo >= 0),
    CONSTRAINT ck_stock_optimo   CHECK (stock_optimo >= stock_minimo)
);


CREATE TABLE ventas (
    venta_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    almacen_id  INT NOT NULL REFERENCES almacenes (almacen_id),
    fecha       TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario     VARCHAR(63) NOT NULL DEFAULT current_user,
    cliente     VARCHAR(100)
);

-- precio_unitario es el precio al momento de la venta
CREATE TABLE detalle_venta (
    venta_id         INT NOT NULL REFERENCES ventas (venta_id),
    linea            SMALLINT NOT NULL,
    producto_id      INT NOT NULL REFERENCES productos (producto_id),
    cantidad         INT NOT NULL,
    precio_unitario  NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (venta_id, linea),
    CONSTRAINT uq_detalle_venta_producto UNIQUE (venta_id, producto_id),
    CONSTRAINT ck_detalle_linea    CHECK (linea > 0),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio   CHECK (precio_unitario >= 0)
);

-- Un producto por transferencia
CREATE TABLE transferencias (
    transferencia_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    almacen_origen_id   INT NOT NULL REFERENCES almacenes (almacen_id),
    almacen_destino_id  INT NOT NULL REFERENCES almacenes (almacen_id),
    producto_id         INT NOT NULL REFERENCES productos (producto_id),
    cantidad            INT NOT NULL,
    estado              VARCHAR(12) NOT NULL DEFAULT 'EN_TRANSITO',
    fecha_envio         TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_recepcion     TIMESTAMPTZ,
    usuario             VARCHAR(63) NOT NULL DEFAULT current_user,
    CONSTRAINT ck_transf_almacenes_distintos CHECK (almacen_origen_id <> almacen_destino_id),
    CONSTRAINT ck_transf_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_transf_estado   CHECK (estado IN ('EN_TRANSITO', 'RECIBIDA')),
    CONSTRAINT ck_transf_recepcion
        CHECK ((estado = 'RECIBIDA') = (fecha_recepcion IS NOT NULL)),
    CONSTRAINT ck_transf_fechas
        CHECK (fecha_recepcion IS NULL OR fecha_recepcion >= fecha_envio)
);

-- Un movimiento viene de una venta, de una transferencia o de ninguna
CREATE TABLE movimientos_inventario (
    movimiento_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id       INT NOT NULL REFERENCES productos (producto_id),
    almacen_id        INT NOT NULL REFERENCES almacenes (almacen_id),
    tipo              VARCHAR(7) NOT NULL,
    cantidad          INT NOT NULL,
    precio_unitario   NUMERIC(12,2) NOT NULL,
    fecha             TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario           VARCHAR(63) NOT NULL DEFAULT current_user,
    venta_id          INT REFERENCES ventas (venta_id),
    transferencia_id  INT REFERENCES transferencias (transferencia_id),
    CONSTRAINT ck_mov_tipo     CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_mov_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_mov_precio   CHECK (precio_unitario >= 0),
    CONSTRAINT ck_mov_un_origen
        CHECK (venta_id IS NULL OR transferencia_id IS NULL),
    CONSTRAINT ck_mov_venta_es_salida
        CHECK (venta_id IS NULL OR tipo = 'SALIDA')
);

CREATE INDEX ix_productos_categoria  ON productos (categoria_id);
CREATE INDEX ix_productos_proveedor  ON productos (proveedor_id);
CREATE INDEX ix_stock_almacen        ON stock_almacen (almacen_id);
CREATE INDEX ix_ventas_almacen       ON ventas (almacen_id);
CREATE INDEX ix_transf_origen        ON transferencias (almacen_origen_id);
CREATE INDEX ix_transf_destino       ON transferencias (almacen_destino_id);
CREATE INDEX ix_mov_almacen_fecha    ON movimientos_inventario (almacen_id, fecha);
CREATE INDEX ix_mov_producto_fecha   ON movimientos_inventario (producto_id, fecha);